#!/bin/sh
# Operation IDs and revisions contain no configuration values or secret hashes.
tt_id_valid() { [ "${#1}" -eq 16 ] && printf '%s' "$1" | grep -Eq '^[0-9a-f]{16}$'; }
tt_revision() {
    if [ -f "$TT_CONFIG/revision" ]; then cat "$TT_CONFIG/revision"; else printf '0\n'; fi
}
tt_revision_advance() {
    TT_REV_TMP=$(mktemp "$TT_CONFIG/.revision.XXXXXX") || return 1
    if od -An -N8 -tx1 /dev/urandom | tr -d ' \n' >"$TT_REV_TMP" &&
        [ "$(wc -c <"$TT_REV_TMP")" -eq 16 ] && mv -f "$TT_REV_TMP" "$TT_CONFIG/revision"; then return 0; fi
    rm -f "$TT_REV_TMP"; return 1
}
tt_revision_check() {
    [ "$1" = "$(tt_revision)" ] || { tt_error 'configuration changed; reload before applying'; return 1; }
}
tt_operation_write() {
    # ID/action/state/code are allowlisted before this function; never error text.
    TT_OP_FILE="$TT_RUN/operations/$TT_OP_ID.json"
    TT_OP_TMP=$(mktemp "$TT_RUN/operations/.op.XXXXXX") || return 1
    if jq -n --arg id "$TT_OP_ID" --arg action "$TT_OP_ACTION" --arg state "$1" --arg code "$2" \
        --arg revision "$(tt_revision)" --argjson time "$(date +%s)" \
        '{id:$id,action:$action,state:$state,code:$code,revision:$revision,updated_at:$time}' >"$TT_OP_TMP" &&
        mv -f "$TT_OP_TMP" "$TT_OP_FILE"; then return 0; fi
    rm -f "$TT_OP_TMP"; return 1
}
tt_operation_begin() {
    tt_id_valid "$1" || return 1
    case "$2" in start|pause|restart|disable|check_updates|update_client|channel_stable|channel_nightly|verify_traffic|endpoint|policy|exclusions|diagnostics|restore-endpoint|restore-policy) :;; *) return 1;; esac
    TT_OP_ID=$1; TT_OP_ACTION=$2
    mkdir -p "$TT_RUN/operations" && chmod 700 "$TT_RUN/operations" || return 1
    # Never rerun even a failed ID; a retry is a new explicit operation.
    [ ! -e "$TT_RUN/operations/$TT_OP_ID.json" ] || return 2
    # Bound storage without removing still-running operations.
    for TT_OLD_OP in "$TT_RUN"/operations/*.json; do
        [ -f "$TT_OLD_OP" ] || continue
        if jq -e --argjson now "$(date +%s)" '.state!="running" and .updated_at<($now-86400)' "$TT_OLD_OP" >/dev/null 2>&1; then rm -f "$TT_OLD_OP"; fi
    done
    TT_OP_COUNT=$(find "$TT_RUN/operations" -type f -name '*.json' | wc -l)
    [ "$TT_OP_COUNT" -lt 256 ] || { tt_error 'operation history full; retry after expiry'; return 1; }
    tt_operation_write running accepted
}
tt_operations_json() {
    if [ ! -d "$TT_RUN/operations" ]; then printf '[]\n'; return; fi
    # Files are generated by this controller; limit public history to recent items.
    find "$TT_RUN/operations" -type f -name '*.json' -exec cat {} \; | jq -s 'sort_by(.updated_at)|reverse|.[0:16]'
}
