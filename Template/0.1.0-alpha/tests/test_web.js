'use strict';
const assert = require('node:assert/strict');
const api = require('../addon/web/trusttunnel.js');
const p = api.policyFromFields('br1', '192.168.50.0/24\n10.0.0.1/32', '1.1.1.1', true);
assert.equal(p.sources.length, 2);
assert.equal(p.table, 871);
assert.throws(() => api.policyFromFields('eth0','192.168.0.0/24','1.1.1.1',true));
assert.throws(() => api.policyFromFields('br1','192.168.0.0/24','1.1.1.1',false));
assert.throws(() => api.policyFromFields('br1','1.2.3.4;reboot','1.1.1.1',true));
assert.throws(() => api.policyFromFields('br1','192.168.0.0/24,192.168.0.0/24','1.1.1.1',true));
const old = {other_addon: 'preserve-me'};
const result = JSON.parse(api.makeEnvelope(old,p));
assert.equal(result.other_addon,'preserve-me');
assert.deepEqual(JSON.parse(atob(result.ttm_policy)),p);
assert.deepEqual(old,{other_addon:'preserve-me'});
assert.throws(() => api.makeEnvelope({other: 'x'.repeat(7600)}, p));
console.log('WebUI: 10 assertions passed');
